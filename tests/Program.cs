sealed class TestWorld:IFurnaceWorld {
    public readonly System.Collections.Generic.Dictionary<Offset,Cell> Cells=new();
    private int fuel=40;
    public TestWorld(){foreach(var r in FurnaceLayout.Build())Cells[r.Position]=new(r.Part,r.Part is Part.Brick or Part.Container or Part.Grate or Part.AirInlet?3:0);}
    public Cell? Read(Offset p)=>Cells.TryGetValue(p,out var c)?c:null;
    public bool TryConsumeCoke(Offset p){if(fuel<=0||Read(p)?.Part!=Part.Coke)return false;fuel--;return true;}
    public bool TryDamageBrick(Offset p,int tier){if(Read(p) is not {Damaged:false} c||c.Part is not (Part.Brick or Part.Grate)||c.Tier!=tier)return false;Cells[p]=c with {Damaged=true};return true;}
}
